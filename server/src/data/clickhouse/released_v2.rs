//! The **released** v2 column sets, recorded rather than derived.
//!
//! `every_clickhouse_migration_applies_to_the_state_it_upgrades` builds its "v2" database by reversing what
//! each migration adds to the *current* schema. That is correct only while the newest migration is the one
//! being tested: once a v4 exists the loop tests v3 against fresh-v4-minus-v3, which is not released v2 - so a
//! v3 regression depending on a v4 column passes while a real upgrade fails. The subtract-from-current shape is
//! this repository's recurring defect and it had survived here.
//!
//! Extracted once from `git show v1.0.13:server/src/data/clickhouse/schema.rs`. A **fact about a released
//! artefact**, so it is frozen: no later schema may change it.
//!
//! **Types, not only names.** Comparing names alone let the reconstructed database differ in type, nullability
//! or width while passing - and a migration applied to a source whose column types are wrong is tested against
//! a schema no database has. `CODEC` and `DEFAULT` are excluded deliberately: those are compression and value
//! policy rather than shape, and `system.columns` normalises defaults in a way that would turn this into a
//! comparison of ClickHouse's own formatting.

